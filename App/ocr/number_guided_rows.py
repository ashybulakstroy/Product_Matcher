"""Conservative number-guided physical row verification for Torgsoft receipts.

An extension of App.ocr.grid_first_rows, not a replacement OCR/parser.
Uses already recognized OCR coordinates and independently observed printed grid.
No catalog, arithmetic ground truth, network, or new OCR models.
"""
from __future__ import annotations

from collections import Counter
from copy import deepcopy
import os
from pathlib import Path
import re
from typing import Any

import numpy as np
from dotenv import dotenv_values

VERSION = "number-guided-rows-v1.0"
_VALID_MODES = frozenset({"off", "shadow", "select"})
_PAYABLE = frozenset({"product", "service", "tax"})


def configured_mode(root: Path | None = None) -> str:
    """Use the existing single project .env; never create an auxiliary config.

    Environment variables from a running process override .env for tests.
    """
    if root is None:
        root = Path(__file__).resolve().parents[2]
    value = os.environ.get("OCR_NUMBER_GUIDED_ROWS_MODE")
    if value is None:
        value = dotenv_values(root / ".env", encoding="utf-8-sig").get("OCR_NUMBER_GUIDED_ROWS_MODE")
    value = str(value or "shadow").strip().lower()
    if value not in _VALID_MODES:
        raise ValueError("OCR_NUMBER_GUIDED_ROWS_MODE must be off, shadow or select")
    return value


def parse_index(raw: Any) -> int | None:
    """Only actual printed Arabic numeral OCR counts; no inferred sequence."""
    s = str(raw or "").strip()  # Never join distinct OCR glyph groups like "1 2"
    if re.fullmatch(r"[0-9]{1,3}", s, flags=re.ASCII):
        n = int(s)
        return n if 1 <= n <= 999 else None
    return None


def _box(line: dict) -> np.ndarray | None:
    try:
        points = np.asarray(line.get("eval_box", line.get("box")), dtype=float)
        if points.shape == (4, 2) and np.isfinite(points).all():
            return points
    except (ValueError, TypeError):
        pass
    return None


def _center(line: dict) -> tuple[float, float] | None:
    box = _box(line)
    if box is not None:
        c = box.mean(axis=0)
        return float(c[0]), float(c[1])
    # Aligned OCR lines generated by App also expose center.
    c = line.get("center")
    if isinstance(c, (list, tuple)) and len(c) == 2:
        try:
            return float(c[0]), float(c[1])
        except (TypeError, ValueError):
            pass
    return None


def number_anchors(aligned: list[dict], layout: dict, *, min_confidence: float = .30) -> list[dict]:
    """Read numbers only from the narrow printed № column, not from names/prices.

    Multiple OCR boxes supporting one number are reconciled by physical y.
    Conflicting numbers in the same y-zone explicitly fail selection.
    """
    left = float(layout.get("body_left", 0))
    right = float(layout["name_left"])
    top = float(layout["body_top"])
    bottom = float(layout["body_bottom"])
    cell_width = right - left
    if cell_width < 12:
        return []
    anchors = []
    for line in aligned:
        index = parse_index(line.get("text"))
        center = _center(line)
        if index is None or center is None:
            continue
        x, y = center
        try:
            confidence = float(line.get("confidence", 0.0))
        except (ValueError, TypeError):
            continue
        if not (top + 4 <= y <= bottom - 3 and left + 2 <= x < right - 1
                and confidence >= min_confidence):
            continue
        box = _box(line)
        if box is not None:
            # Avoid accepting wide merged text spanning name/number columns.
            x0, x1 = float(box[:, 0].min()), float(box[:, 0].max())
            if x0 < left - 2 or x1 > right + 2 or x1-x0 > cell_width * .77:
                continue
        anchors.append(dict(number=index, y=round(y, 3), x=round(x, 3),
                            confidence=round(confidence, 4), text=str(line["text"])))
    anchors.sort(key=lambda a: (a["y"], -a["confidence"]))
    return anchors


def _anchors_in_bands(anchors: list[dict], boundaries: list[float]) -> tuple[list[dict], str]:
    """Match observed number to real physical band, never guess missing numbers."""
    if len(boundaries) < 3:
        return [], "too_few_physical_bands"
    assigned = []
    for anchor in anchors:
        hits = [i+1 for i, (lo, hi) in enumerate(zip(boundaries, boundaries[1:]))
                if lo + 2 <= anchor["y"] < hi - 2]
        if len(hits) != 1:
            continue
        assigned.append(dict(anchor, band=hits[0]))
    # When two OCR detections in the same band disagree, reject all candidates.
    unique_by_band: dict[int, dict] = {}
    for value in assigned:
        previous = unique_by_band.get(value["band"])
        if previous is not None and previous["number"] != value["number"]:
            return assigned, "conflicting_numbers_in_physical_band"
        if previous is None or value["confidence"] > previous["confidence"]:
            unique_by_band[value["band"]] = value
    matched = sorted(unique_by_band.values(), key=lambda a: a["band"])
    if len(matched) < 2:
        return matched, "insufficient_number_evidence"
    if matched[0]["number"] != 1:
        return matched, "first_number_not_one"
    if any(a["number"] != a["band"] for a in matched):
        return matched, "number_disagrees_with_printed_band"
    # The last 1-2 item numbers may be unreadable, but sparse evidence on a
    # 20-row receipt is not enough to authorize reconstruction.
    if len(matched) < max(2, int(np.ceil((len(boundaries)-1)*.45))):
        return matched, "numbers_too_sparse"
    if matched[-1]["band"] < (len(boundaries)-1) - 2:
        return matched, "no_lower_row_number_support"
    return matched, "confirmed"


def _row_sequence_valid(rows: list[dict], anchors: list[dict]) -> bool:
    if not rows or not anchors:
        return False
    for row in rows:
        if row.get("kind") not in _PAYABLE:
            continue
        band = row.get("y_range")
        if not (isinstance(band, (list, tuple)) and len(band) == 2):
            return False
        matches = [a for a in anchors if float(band[0]) + 1 < a["y"] < float(band[1]) - 1]
        # Multiple distinct printed numbers inside one logical row is a split error.
        if len({a["number"] for a in matches}) > 1:
            return False
        raw = parse_index(row.get("item_number_raw"))
        if raw is not None and matches and raw != matches[0]["number"]:
            return False
    return True


def _structural_problem(rows: list[dict], anchors: list[dict], physical_count: int) -> bool:
    payable = [r for r in rows if r.get("kind") in _PAYABLE]
    if len(payable) != physical_count:
        return True
    if not _row_sequence_valid(payable, anchors):
        return True
    for r in payable:
        if parse_index(r.get("item_number_raw")) is not None and parse_index(r["item_number_raw"]) != r.get("row"):
            return True
    return False


def _all_recognized_text(rows: list[dict]) -> Counter:
    # Only words from the name column are compared; numeric layout may improve.
    # Multiplicity prevents silently losing identical item names from another row.
    words = []
    for row in rows:
        if row.get("kind") in _PAYABLE:
            words.extend(re.findall(r"[A-Za-zА-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі0-9]{2,}",
                                    str(row.get("name_raw", "")).lower()))
    return Counter(words)


def refine_number_guided_rows(image, layout: dict, aligned: list[dict], rows: list[dict], *,
                              header_verified: bool = False, mode: str | None = None) -> tuple[list[dict], dict]:
    """Optionally reconstruct if the *printed lines AND numbers* prove a split.

    Nothing is read from ground truth or totals. Candidate uses the existing
    Grid-First reconstruction engine without a second OCR pass.
    Select updates layout's row boundaries only after all hard guards pass.
    """
    chosen_mode = configured_mode() if mode is None else str(mode).lower()
    if chosen_mode not in _VALID_MODES:
        raise ValueError("Invalid number-guided mode")
    report = dict(version=VERSION, mode=chosen_mode, status="not_run", selected=False,
                  initial_payable=sum(r.get("kind") in _PAYABLE for r in rows),
                  anchors=[], bands=[], printed_grid=None, candidate_rows=0, reason="")
    if chosen_mode == "off":
        report.update(status="disabled", reason="mode_off")
        return rows, report
    from App.ocr.grid_first_rows import find_printed_grid_bands, reconstruct_rows
    anchors = number_anchors(aligned, layout)
    report["anchors"] = anchors
    if len(anchors) < 2:
        report.update(status="not_needed", reason="no_reliable_printed_number_sequence")
        return rows, report
    boundaries, grid_report = find_printed_grid_bands(image, layout, aligned, header_verified=header_verified)
    report["printed_grid"] = grid_report
    if not boundaries:
        report.update(status="rejected", reason="no_independent_printed_grid")
        return rows, report
    report["bands"] = [round(float(v), 2) for v in boundaries]
    matched, reason = _anchors_in_bands(anchors, boundaries)
    report["number_band_evidence"] = matched
    if reason != "confirmed":
        report.update(status="rejected", reason=reason)
        return rows, report
    physical_count = len(boundaries) - 1
    if not _structural_problem(rows, anchors, physical_count):
        report.update(status="not_needed", reason="existing_rows_match_numbered_printed_grid")
        return rows, report
    # Call Grid-First on a shallow *copy* of layout and with empty initial rows
    # to force its printed-grid branch. No extra OCR calls or new model loads.
    new_layout = deepcopy(layout)
    candidate, grid_candidate = reconstruct_rows(image, new_layout, aligned, [],
                                                read_name=None, read_numeric=None,
                                                header_verified=header_verified)
    report["candidate_grid_first"] = grid_candidate
    report["candidate_rows"] = len(candidate)
    if grid_candidate.get("strategy") != "printed_grid" or len(candidate) != physical_count:
        report.update(status="rejected", reason="candidate_not_independent_grid")
        return rows, report
    for mark in matched:
        row = candidate[mark["band"] - 1]
        lo, hi = row.get("y_range", (None, None))
        if lo is None or not lo + 2 <= mark["y"] < hi - 2:
            report.update(status="rejected", reason="candidate_number_crossed_row_border")
            return rows, report
        item = parse_index(row.get("item_number_raw"))
        if item is not None and item != mark["number"]:
            report.update(status="rejected", reason="candidate_number_mismatch")
            return rows, report
    original_payable = [r for r in rows if r.get("kind") in _PAYABLE]
    if len(candidate) < len(original_payable):
        report.update(status="rejected", reason="would_drop_existing_rows")
        return rows, report
    tax_before = sum(r.get("kind") == "tax" for r in original_payable)
    tax_after = sum(r.get("kind") == "tax" for r in candidate)
    if (tax_before and tax_after != tax_before) or tax_after > 1:
        report.update(status="rejected", reason="tax_row_not_preserved")
        return rows, report
    before_tokens = _all_recognized_text(original_payable)
    after_tokens = _all_recognized_text(candidate)
    missing_tokens = before_tokens - after_tokens
    if missing_tokens:
        report.update(status="rejected", reason="would_lose_name_evidence",
                      dropped_tokens=dict(missing_tokens))
        return rows, report
    # Need a real change; we do not touch healthy receipts.
    if chosen_mode == "shadow":
        report.update(status="candidate_ready", reason="shadow_no_changes")
        return rows, report
    layout["row_boundaries"] = list(new_layout.get("row_boundaries", layout.get("row_boundaries", [])))
    report.update(status="selected", selected=True, reason="number_and_printed_grid_agree")
    return candidate, report
